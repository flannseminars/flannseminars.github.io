#!/usr/bin/env python3
"""Build the menu, permanent editions, and community-led posts for GitHub Pages."""
import argparse
import html
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

from tasting_menu import safe_url as validate_url, validate_config, validate_scoring

ROOT = Path(__file__).resolve().parents[1]
GENERATED_NOTICE = '<!-- Generated by scripts/build_tasting_menu.py; edit data/tasting-menu-editorial.json. -->'
SLUG = r'[a-z0-9]+(?:-[a-z0-9]+)*'


def escape(value):
    return html.escape(str(value), quote=True)


def safe_url(value):
    return escape(validate_url(value))


def text(record, field, context):
    value = record.get(field)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{context}.{field} must be nonempty text')
    return value


def paragraphs(values, context, required=False):
    if not isinstance(values, list) or (required and not values) or any(not isinstance(v, str) or not v.strip() for v in values):
        raise ValueError(f'{context} must be an array of nonempty paragraphs')


def github_url(value, repository, thread=False):
    url = urlsplit(validate_url(value))
    base = '/' + repository + '/issues'
    is_thread = bool(re.fullmatch(re.escape(base) + r'/[1-9]\d*', url.path))
    if url.netloc != 'github.com' or not (is_thread or (not thread and url.path == base)):
        raise ValueError('Public results and quote sources must link to this repository’s GitHub issues')
    if url.fragment and not re.fullmatch(r'issuecomment-\d+|issue-\d+', url.fragment):
        raise ValueError('Quote sources must use an original GitHub comment anchor')


def validate_editorial(data, config):
    if not isinstance(data, dict) or not isinstance(data.get('papers'), list) or not isinstance(data.get('editions'), list):
        raise ValueError('Editorial data needs editions and papers arrays')
    editions = {}
    for edition in data['editions']:
        if not isinstance(edition, dict):
            raise ValueError('An edition must be an object')
        for field in ('id', 'title', 'label', 'published', 'description', 'validationNote'):
            text(edition, field, 'edition')
        if not re.fullmatch(SLUG, edition['id']) or edition['id'] in editions:
            raise ValueError('Edition IDs must be unique lowercase slugs')
        if type(edition.get('example')) is not bool:
            raise ValueError('edition.example must be a boolean')
        validate_scoring(edition.get('scoring'))
        if not edition['example'] and edition['id'] == config['edition']['id'] and edition['scoring'] != config['scoring']:
            raise ValueError('The current edition scoring must match the announced configuration')
        if not edition['example']:
            github_url(edition.get('resultsUrl'), config['repository'])
        elif edition.get('resultsUrl') is not None:
            raise ValueError('Example editions must not invent public results links')
        editions[edition['id']] = edition
    ids = set()
    for paper in data['papers']:
        if not isinstance(paper, dict):
            raise ValueError('A paper must be an object')
        for field in ('id', 'edition', 'title', 'authors', 'published', 'topic', 'url', 'standfirst', 'hostNote'):
            text(paper, field, 'paper')
        if not re.fullmatch(SLUG, paper['id']) or paper['id'] in ids:
            raise ValueError('Paper IDs must be unique lowercase slugs')
        ids.add(paper['id'])
        edition = editions.get(paper['edition'])
        if not edition:
            raise ValueError('Paper must belong to a declared edition')
        if type(paper.get('example')) is not bool or paper['example'] != edition['example']:
            raise ValueError('Paper example flag must match its edition')
        rules = edition['scoring']
        safe_url(paper['url'])
        paragraphs(paper.get('intro', []), 'paper.intro')
        support = paper.get('support')
        if not isinstance(support, dict) or any(type(support.get(k)) is not int or support[k] < 0 for k in ('recommendations', 'endorsements', 'score')):
            raise ValueError('Support needs nonnegative integer counts and score')
        if support['score'] != support['recommendations'] * rules['recommendation'] + support['endorsements'] * rules['endorsement']:
            raise ValueError('Support score does not match the edition’s weights')
        if support['score'] < rules['threshold']:
            raise ValueError('A published highlight must meet its edition’s threshold')
        reviews = paper.get('endorsements')
        if not isinstance(reviews, list) or not reviews:
            raise ValueError('A highlight needs at least one attributed recommendation')
        displayed_counts = {rules['recommendation']: 0, rules['endorsement']: 0}
        names = set()
        for review in reviews:
            if not isinstance(review, dict):
                raise ValueError('A recommendation must be an object')
            for field in ('text', 'name', 'relationship'):
                text(review, field, 'recommendation')
            if type(review.get('example')) is not bool or review['example'] != paper['example']:
                raise ValueError('Every sample recommendation must be explicitly marked example')
            if type(review.get('weight')) is not int or review['weight'] not in (rules['recommendation'], rules['endorsement']):
                raise ValueError('Recommendation weight must match the edition')
            if review['relationship'] not in ('Independent reader', 'Author / coauthor', 'Other conflict of interest'):
                raise ValueError('Unknown recommendation relationship')
            if review['relationship'] != 'Independent reader' and review['weight'] != 1:
                raise ValueError('Conflicted recommendations can contribute at most one point')
            identity = (review.get('handle') or review['name']).strip().lower()
            if identity in names:
                raise ValueError('Use one attributed excerpt per recommender in a highlight')
            names.add(identity)
            displayed_counts[review['weight']] += 1
            if review['example']:
                if not review['name'].startswith('Example reader ') or review.get('url') is not None:
                    raise ValueError('Sample quotes must use Example reader labels without invented source links')
            else:
                github_url(review.get('url'), config['repository'], thread=True)
        if displayed_counts[rules['recommendation']] > support['recommendations'] or displayed_counts[rules['endorsement']] > support['endorsements']:
            raise ValueError('Displayed quote counts cannot exceed the final tally for their weight')
        guide = paper.get('authorGuide')
        if guide is not None:
            if not isinstance(guide, dict) or type(guide.get('example')) is not bool or guide['example'] != paper['example']:
                raise ValueError('An authorGuide must explicitly match the paper’s example state')
            for field in ('by', 'title'):
                text(guide, field, 'authorGuide')
            paragraphs(guide.get('paragraphs', []), 'authorGuide.paragraphs')
            if guide.get('videoUrl'):
                safe_url(guide['videoUrl'])
            if not guide.get('paragraphs') and not guide.get('videoUrl'):
                raise ValueError('An authorGuide needs written content or a video')
        if not paper['example']:
            github_url(paper.get('discussionUrl'), config['repository'], thread=True)
    return editions


def link(url, label, css=''):
    return f'<a class="{css}" href="{safe_url(url)}">{escape(label)}</a>'


def navigation(prefix):
    pages = [('index.html', 'Home'), ('schedule.html', 'Schedule'), ('team.html', 'Team'), ('resources.html', 'Resources'), ('workshop.html', 'Workshop'), ('tasting-menu.html', 'Tasting Menu')]
    return ''.join(f'<li><a href="{prefix}{path}"' + (' class="active"' if path == 'tasting-menu.html' else '') + f'>{label}</a></li>' for path, label in pages)


def shell(title, description, content, prefix='../../'):
    return f'''<!doctype html>
{GENERATED_NOTICE}
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)} · FLaNN Tasting Menu</title><meta name="description" content="{escape(description)}">
<link rel="icon" type="image/webp" href="{prefix}img/flann.webp"><link rel="stylesheet" href="{prefix}style.css"><link rel="stylesheet" href="{prefix}tasting-menu.css"></head>
<body class="tasting-page"><a href="#main" class="skip-link">Skip to content</a><div class="wrapAll clearfix">
<aside class="sidebar"><div class="logo"><a href="{prefix}index.html"><img src="{prefix}img/flann.webp" alt="FLaNN Seminars home"></a></div><nav class="navigation" aria-label="Main navigation"><ul>{navigation(prefix)}</ul></nav><a class="tm-rail-archive" href="{prefix}tasting-menu/archive.html">All editions →</a></aside>
<div class="mainsection"><div class="tabs clearfix"><nav class="tabsLeft" aria-label="Page navigation"><ul>{navigation(prefix)}</ul></nav></div>
<main id="main" class="article"><div class="tm-wrap">{content}<footer class="tm-footer"><span>FLaNN Seminars · The Tasting Menu</span><a href="{prefix}tasting-menu/archive.html">All editions →</a><a href="{prefix}tasting-menu.html#nominate">Suggest a paper →</a></footer></div></main></div></div></body></html>
'''


def quote_markup(review, index):
    if review['example']:
        return ''
    label = 'Enthusiastic endorsement' if review['weight'] > 1 else 'Recommendation'
    source = link(review['url'], 'Original public comment ↗', 'tm-quote-source')
    name = escape(review['name'])
    handle = '<span>@' + escape(review['handle']) + '</span>' if review.get('handle') else ''
    return f'''<figure class="tm-reader-quote"><div class="tm-quote-level">{escape(label)} <b>+{review['weight']}</b></div><blockquote>“{escape(review['text'])}”</blockquote><figcaption><span class="tm-reader-initial" aria-hidden="true">{escape(review['name'].split()[-1][:1])}</span><span><strong>{name}</strong>{handle}<small>{escape(review['relationship'])}</small></span></figcaption>{source}</figure>'''


def support_note(paper, edition):
    counts = paper['support']
    total = counts['recommendations'] + counts['endorsements']
    return f'''<aside class="tm-post-tally"><div class="tm-post-score">{total} <span>{'endorsement' if total == 1 else 'endorsements'}</span></div><p>{counts['recommendations']} {'recommendation' if counts['recommendations'] == 1 else 'recommendations'} · {counts['endorsements']} strong {'endorsement' if counts['endorsements'] == 1 else 'endorsements'}</p></aside>'''


def paper_page(paper, edition):
    example = paper['example']
    intro = '' if example else ''.join('<p>' + escape(p) + '</p>' for p in paper.get('intro', []))
    quotes = ''.join(quote_markup(review, index) for index, review in enumerate(paper['endorsements']))
    intro_section = '<div class="tm-prose tm-editor-note">' + intro + '</div>' if intro else ''
    comments = '<div class="tm-community-voices">' + quotes + '</div>' if quotes else '<p class="tm-note">Reader comments will appear here.</p>'
    guide_html = ''
    guide = paper.get('authorGuide')
    if guide and not guide['example']:
        content = ''.join('<p>' + escape(p) + '</p>' for p in guide.get('paragraphs', []))
        video = link(guide['videoUrl'], 'Watch the authors’ video guide ↗', 'tm-button secondary') if guide.get('videoUrl') else ''
        guide_html = f'<section class="tm-author-guide" id="author-guide"><div class="tm-kicker">From the authors</div><h2>{escape(guide["title"])}</h2><p class="tm-guide-byline">By {escape(guide["by"])}</p>{content}{video}</section>'
    host_note = ''
    if not example:
        result = link(paper['discussionUrl'], 'Public recommendations ↗', 'tm-text-link')
        host_note = f'<section class="tm-host-note"><div class="tm-kicker">After the public vote</div><p>{escape(paper["hostNote"])}</p>{result}</section>'
    guide_link = '<a href="#author-guide">Author guide ↓</a>' if guide_html else ''
    content = f'''<nav class="tm-breadcrumb" aria-label="Within the tasting menu"><a href="../../tasting-menu.html">Tasting Menu</a><span>/</span><a href="../editions/{edition['id']}.html">{escape(edition['label'])}</a><span>/</span><a href="../archive.html">All editions</a></nav>
<article class="tm-blog"><header class="tm-blog-head"><div class="tm-kicker">{escape(paper['topic'])} · {escape(paper['published'])}</div><h1>{escape(paper['title'])}</h1><p class="tm-authors">{escape(paper['authors'])}</p><p class="tm-standfirst">{escape(paper['standfirst'])}</p><div class="tm-actions">{link(paper['url'], 'Read the paper ↗', 'tm-button')}{guide_link}<a href="#reader-comments">Readers’ comments ↓</a></div></header>
<div class="tm-post-layout"><div class="tm-post-main">{intro_section}<section id="reader-comments"><div class="tm-heading"><h2>Reader comments</h2></div>{comments}</section>{guide_html}{host_note}</div>{support_note(paper,edition)}</div></article>'''
    return shell(paper['title'], paper['standfirst'], content)


def menu_markup(papers, edition, prefix='', heading='h2'):
    rows = ''
    for number, paper in enumerate(papers, 1):
        authors = paper['authors'] if len(paper['authors']) < 100 else paper['authors'].split(',')[0] + ' et al.'
        count = paper['support']['recommendations'] + paper['support']['endorsements']
        breakdown = f"{paper['support']['recommendations']} recommendations; {paper['support']['endorsements']} strong endorsements"
        rows += f'''<article class="tm-menu-entry"><div class="tm-course-number">{number:02d}</div><div class="tm-menu-body"><div class="tm-dish-line"><h3><a href="{prefix}tasting-menu/papers/{paper['id']}.html">{escape(paper['title'])}</a></h3><div class="tm-menu-score" title="{escape(breakdown)}">{count}<small>{'endorsement' if count == 1 else 'endorsements'}</small></div></div><p class="tm-menu-authors">{escape(authors)}</p></div></article>'''
    if not rows:
        rows = '<p class="tm-note">The papers for this serving will appear after public voting and the hosts’ checks.</p>'
    return f'''<div class="tm-menu-sheet"><header class="tm-menu-masthead"><{heading}>The tasting menu</{heading}><p>{escape(edition['label'])}</p></header><div class="tm-menu-entries">{rows}</div></div>'''


def edition_cards(editions, papers, prefix=''):
    cards = []
    for edition in editions:
        count = sum(p['edition'] == edition['id'] for p in papers)
        date = '' if edition['example'] else ' · ' + escape(edition['published'])
        cards.append(f'''<a class="tm-edition-card" href="{prefix}tasting-menu/editions/{edition['id']}.html"><strong>{escape(edition['label'])}</strong><span>{count} {'papers' if count != 1 else 'paper'}{date}</span><b>View edition →</b></a>''')
    return '<div class="tm-edition-grid">' + ''.join(cards) + '</div>' if cards else '<p class="tm-note">No editions have been published yet. Each menu will have a permanent place here.</p>'


def archive_page(editions, papers):
    content = '<nav class="tm-breadcrumb"><a href="../tasting-menu.html">← Current menu</a></nav><header class="tm-archive-head"><h1>All editions</h1></header>' + edition_cards(editions, papers, '../')
    return shell('All editions', 'Browse every FLaNN Tasting Menu edition and its original recommendations.', content, '../')


def edition_page(edition, papers):
    record = ''
    if not edition['example']:
        results = link(edition['resultsUrl'], 'Final results on GitHub ↗', 'tm-button secondary')
        rules = edition['scoring']
        record = f'''<section class="tm-edition-record"><h2>Public record</h2><p>{escape(edition['published'])} · +{rules['recommendation']} recommendation · +{rules['endorsement']} endorsement · {rules['threshold']}-point threshold</p><p>{escape(edition['validationNote'])}</p>{results}</section>'''
    content = f'''<nav class="tm-breadcrumb"><a href="../../tasting-menu.html">Current menu</a><span>/</span><a href="../archive.html">All editions</a></nav>{menu_markup(papers,edition,'../../',heading='h1')}{record}'''
    return shell(edition['title'], edition['description'], content)


def replace_once(pattern, replacement, source, label):
    updated, count = re.subn(pattern, replacement, source, flags=re.S)
    if count != 1:
        raise ValueError(f'Expected exactly one {label} region in tasting-menu.html')
    return updated


def static_round_text(config):
    edition = config['edition']
    if config['preview']:
        return ('Nominations open soon', 'Next edition', 'Prepare a recommendation for the next round.')
    if edition['status'] == 'open':
        return (f"Nomination window: {edition['opens']} – {edition['closes']}", 'Prepare a public nomination', f"The announced window is {edition['opens']} to {edition['closes']}. Prepare a draft here, then review and post it on GitHub. JavaScript checks whether the window is currently open.")
    status = {'planning':'Nominations have not opened','review':'Host checks in progress','closed':'Nominations closed','published':'Edition published'}[edition['status']]
    return status, edition['title'], 'Submissions are not open. Read the public recommendations and browse published editions.'


def render(check=False, root=None):
    root = Path(root) if root is not None else ROOT
    config = json.loads((root / 'data/tasting-menu.json').read_text())
    validate_config(config)
    data = json.loads((root / 'data/tasting-menu-editorial.json').read_text())
    by_id = validate_editorial(data, config)
    editions = [e for e in data['editions'] if config['preview'] or not e['example']]
    papers = [p for p in data['papers'] if config['preview'] or not p['example']]
    current = by_id.get(config['edition']['id'])
    if current is None and config['preview']:
        current = next((e for e in editions if e['example']), None)
    if current and current not in editions:
        current = None
    current_papers = [p for p in papers if current and p['edition'] == current['id']]
    highlights = menu_markup(current_papers,current) if current else '<div class="tm-empty"><strong>The next menu is taking shape.</strong><p>Papers meeting the public threshold will appear after the hosts’ checks.</p></div>'
    index_path = root / 'tasting-menu.html'
    index = index_path.read_text()
    for region, content in [('highlights',highlights),('archive',edition_cards([e for e in editions if not current or e['id'] != current['id']],papers))]:
        index = replace_once(r'<!-- '+region+r':start -->.*?<!-- '+region+r':end -->', lambda _: '<!-- '+region+':start -->\n'+content+'\n<!-- '+region+':end -->', index, region)
    values = {}
    values['snapshot-date'],values['form-mode'],values['form-explanation'] = static_round_text(config)
    values['draft-button'] = 'Prepare draft →'
    rules=config['scoring']
    for element_id,value in values.items():
        pattern=r'(<(?P<tag>span|p|button)\b[^>]*\bid="'+re.escape(element_id)+r'"[^>]*>).*?(</(?P=tag)>)'
        index=replace_once(pattern,lambda m:m[1]+escape(value)+m[3],index,element_id)
    index=re.sub(r'(<span data-score="([A-Za-z]+)">).*?(</span>)',lambda m:m[1]+str(rules[m[2]])+m[3],index)
    if config['preview']:
        fallback='<div class="tm-empty"><p>No nominations yet.</p><a href="#nominate" class="tm-text-link">Recommend a paper →</a></div>'
    else:
        url='https://github.com/'+config['repository']+'/issues?q=is%3Aissue+label%3Atasting-menu'
        fallback='<div class="tm-empty"><strong>Explore the public recommendations.</strong><p>JavaScript displays the latest published snapshot here.</p>'+link(url,'Read nominations on GitHub ↗','tm-text-link')+'</div>'
    index=replace_once(r'(<div id="nominations"[^>]*>).*?(</div>\s*<noscript>)',lambda m:m[1]+fallback+m[2],index,'nomination fallback')
    outputs={index_path:index,root/'tasting-menu/archive.html':archive_page(editions,papers)}
    outputs.update({root/'tasting-menu/papers'/(p['id']+'.html'):paper_page(p,by_id[p['edition']]) for p in papers})
    outputs.update({root/'tasting-menu/editions'/(e['id']+'.html'):edition_page(e,[p for p in papers if p['edition']==e['id']]) for e in editions})
    managed={path for path in (root/'tasting-menu').rglob('*.html') if GENERATED_NOTICE in path.read_text()}
    obsolete=sorted(managed-set(outputs))
    stale=[str(path.relative_to(root)) for path,content in outputs.items() if not path.exists() or path.read_text()!=content]
    if check:
        if stale or obsolete:
            raise ValueError('Generated pages need rebuilding: '+', '.join(stale+[str(p.relative_to(root))+' (remove)' for p in obsolete]))
    else:
        for path,content in outputs.items():
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
        for path in obsolete:
            path.unlink()
    print(f"{'Checked' if check else 'Built'} {len(outputs)} Tasting Menu pages.")


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Check that all generated pages are current')
    args=parser.parse_args()
    try:
        render(args.check)
    except (ValueError,KeyError,TypeError) as error:
        parser.exit(1,f'{error}\n')
