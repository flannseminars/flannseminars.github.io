#!/usr/bin/env python3
"""Render reviewed reading notes as ordinary GitHub Pages HTML. No dependencies."""
import argparse
import html
import json
import re
from pathlib import Path

from tasting_menu import safe_url as validate_url, validate_config

ROOT = Path(__file__).resolve().parents[1]
GENERATED_NOTICE = '<!-- Generated by scripts/build_tasting_menu.py; edit data/tasting-menu-editorial.json. -->'


def escape(value):
    return html.escape(str(value), quote=True)


def safe_url(value):
    return escape(validate_url(value))


def required_text(record, field, context):
    value = record.get(field)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f'{context}.{field} must be nonempty text')
    return value


def validate_editorial(data, config):
    """Validate every record before rendering, including hidden preview entries."""
    if not isinstance(data, dict) or not isinstance(data.get('papers'), list):
        raise ValueError('Editorial data must contain a papers array')
    ids, editions = set(), {}
    for number, paper in enumerate(data['papers']):
        context = f'papers[{number}]'
        if not isinstance(paper, dict):
            raise ValueError(f'{context} must be an object')
        for field in ('id', 'edition', 'title', 'authors', 'published', 'topic', 'url',
                      'standfirst', 'whyRead', 'caveat'):
            required_text(paper, field, context)
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', paper['id']) or paper['id'] in ids:
            raise ValueError('Paper IDs must be unique, lowercase, hyphenated slugs')
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', paper['edition']):
            raise ValueError(f'{context}.edition must be a lowercase slug')
        ids.add(paper['id'])
        if 'example' in paper and type(paper['example']) is not bool:
            raise ValueError(f'{context}.example must be true or false')
        for field in ('summary', 'readingGuide'):
            values = paper.get(field)
            if not isinstance(values, list) or not values or any(not isinstance(item, str) or not item.strip() for item in values):
                raise ValueError(f'{context}.{field} must be a nonempty array of text')
        safe_url(paper['url'])
        for field in ('video', 'discussionUrl'):
            if paper.get(field) is not None:
                safe_url(required_text(paper, field, context))
        if paper.get('selectionReason') is not None:
            required_text(paper, 'selectionReason', context)
        endorsements = paper.get('endorsements', [])
        if not isinstance(endorsements, list):
            raise ValueError(f'{context}.endorsements must be an array')
        if paper.get('example') and endorsements:
            raise ValueError('Preview examples must not contain community endorsements')
        for index, quote in enumerate(endorsements):
            quote_context = f'{context}.endorsements[{index}]'
            if not isinstance(quote, dict):
                raise ValueError(f'{quote_context} must be an object')
            for field in ('text', 'name', 'relationship', 'url'):
                required_text(quote, field, quote_context)
            safe_url(quote['url'])
        if not paper.get('example'):
            required_text(paper, 'selectionReason', context)
            required_text(paper, 'discussionUrl', context)
            editions.setdefault(paper['edition'], []).append(paper)
            if len(editions[paper['edition']]) > config['maxPapers']:
                raise ValueError('An edition exceeds the configured paper limit')
    return editions


def replace_once(pattern, replacement, source, label):
    updated, count = re.subn(pattern, replacement, source, flags=re.S)
    if count != 1:
        raise ValueError(f'Expected exactly one {label} region in tasting-menu.html')
    return updated


def static_round_text(config):
    """Date ranges stay accurate when a static page outlives an open window."""
    edition = config['edition']
    if config['preview']:
        return ('Pilot round · not open yet', 'Try the nomination draft',
                'Preview the submission flow below. This creates a draft on your device; nothing is sent or counted. When the round opens, contributors will review and post it on GitHub.')
    if edition['status'] == 'open':
        return (f"Nomination window: {edition['opens']} – {edition['closes']}",
                'Prepare a public nomination',
                f"Nominations are accepted within the announced window, {edition['opens']} to {edition['closes']}. Drafts stay on your device until you review and post them on GitHub. JavaScript checks whether the window is currently open.")
    messages = {
        'planning': ('Nominations have not opened', 'Dates and the eligible paper window will be announced before nominations open.'),
        'review': ('Editorial review', 'The nomination window has closed. Editors are reviewing the public recommendations.'),
        'closed': ('Nominations closed', 'The nomination window has closed. Read the public discussion and published highlights.'),
        'published': ('Edition published', 'This edition has been published. Read its highlights and the original public recommendations.'),
    }
    status, message = messages[edition['status']]
    return (status, 'Prepare a draft for a future round', message + ' You may prepare a local draft; nothing is submitted or counted here.')


def link(url, label, css=""):
    return f'<a class="{css}" href="{safe_url(url)}">{escape(label)}</a>'


def navigation(prefix):
    pages = [("index.html", "Home"), ("schedule.html", "Schedule"), ("team.html", "Team"),
             ("resources.html", "Resources"), ("workshop.html", "Workshop"), ("tasting-menu.html", "Tasting Menu")]
    return "".join(f'<li><a href="{prefix}{path}"' + (' class="active"' if path == "tasting-menu.html" else '') + f'>{label}</a></li>' for path, label in pages)


def paper_page(paper):
    prefix = "../../"
    title = escape(paper["title"])
    example = paper.get("example", False)
    notice = '<div class="tm-preview"><strong>Example highlight</strong><span>A layout demonstration using an existing FLaNN resource. This is not a community selection.</span></div>' if example else ''
    summary = "".join(f'<p>{escape(p)}</p>' for p in paper["summary"])
    guide = "".join(f'<li>{escape(p)}</li>' for p in paper["readingGuide"])
    if paper.get("video"):
        video = link(paper["video"], "Watch the companion video ↗", "tm-button secondary")
    else:
        video = '<div class="tm-video-placeholder"><strong>No companion video yet.</strong><p>A short walkthrough or seminar recording can be added here when available.</p></div>'
    quotes = ""
    for quote in paper.get("endorsements", []):
        quotes += '<blockquote><p>“' + escape(quote["text"]) + '”</p><cite>' + link(quote["url"], quote["name"]) + ' · ' + escape(quote["relationship"]) + '</cite></blockquote>'
    if not quotes:
        quotes = '<p class="tm-note">No community endorsements are presented in this example. A published highlight will include attributed excerpts linked to the original public discussion.</p>' if example else '<p class="tm-note">Read the public discussion for the full recommendations.</p>'
    discussion = link(paper["discussionUrl"], "Read the public discussion ↗", "tm-text-link") if paper.get("discussionUrl") else ''
    selection = '<h2>Why this made the menu</h2><p>' + escape(paper["selectionReason"]) + '</p>' if paper.get("selectionReason") else ''
    return f'''<!doctype html>
{GENERATED_NOTICE}
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} · FLaNN Tasting Menu</title><meta name="description" content="{escape(paper['standfirst'])}">
<link rel="icon" type="image/webp" href="{prefix}img/flann.webp"><link rel="stylesheet" href="{prefix}style.css"><link rel="stylesheet" href="{prefix}tasting-menu.css"></head>
<body class="tasting-page"><a href="#main" class="skip-link">Skip to content</a><div class="wrapAll clearfix">
<aside class="sidebar"><div class="logo"><a href="{prefix}index.html"><img src="{prefix}img/flann.webp" alt="FLaNN Seminars home"></a></div><nav class="navigation" aria-label="Main navigation"><ul>{navigation(prefix)}</ul></nav></aside>
<div class="mainsection"><div class="tabs clearfix"><nav class="tabsLeft" aria-label="Page navigation"><ul>{navigation(prefix)}</ul></nav></div>
<main id="main" class="article"><article class="tm-wrap tm-detail">
{notice}<a href="{prefix}tasting-menu.html#on-the-menu" class="tm-text-link">← Back to the Tasting Menu</a>
<header class="tm-detail-head"><div class="tm-kicker">{escape(paper['topic'])} · {escape(paper['published'])}</div><h1>{title}</h1><p class="tm-authors">{escape(paper['authors'])}</p><p class="tm-standfirst">{escape(paper['standfirst'])}</p><div class="tm-actions">{link(paper['url'], 'Read the paper ↗', 'tm-button')}<a href="#video">Companion video ↓</a></div></header>
<div class="tm-prose"><h2>The idea, briefly</h2>{summary}<p class="tm-note">Editorial overview based on {link(paper['url'], 'the paper’s abstract')}. Reading suggestions below are editorial guidance.</p>
<h2>Why spend time here?</h2><p>{escape(paper['whyRead'])}</p><h2>A way into the paper</h2><ul>{guide}</ul><aside class="tm-caveat"><strong>Keep in mind</strong><p>{escape(paper['caveat'])}</p></aside>
<h2 id="video">Watch &amp; discuss</h2>{video}{selection}<h2>From the community</h2><div class="tm-quotes">{quotes}</div>{discussion}</div>
<footer class="tm-footer"><span>FLaNN Seminars · The Tasting Menu</span><a href="{prefix}tasting-menu.html#nominate">Suggest a paper →</a></footer>
</article></main></div></div></body></html>
'''


def card(paper, number):
    authors = paper["authors"]
    if len(authors) > 110:
        authors = authors.split(",")[0] + " et al."
    label = 'Example reading note · not an endorsement' if paper.get('example') else 'Editor’s reading note'
    return f'''<article class="tm-paper"><div class="tm-number" aria-hidden="true">{number:02d}</div><div>
<div class="tm-kicker">{escape(paper['topic'])} · {escape(paper['published'])}</div>
<h3><a href="tasting-menu/papers/{paper['id']}.html">{escape(paper['title'])}</a></h3><p class="tm-authors">{escape(authors)}</p>
<p class="tm-summary">{escape(paper['standfirst'])}</p><a href="tasting-menu/papers/{paper['id']}.html" class="tm-text-link">Read the highlight →</a></div>
<aside class="tm-serving"><div class="tm-kicker">A good read for…</div><p>{escape(paper['whyRead'])}</p><small>{label}</small></aside></article>'''


def render(check=False, root=None):
    root = Path(root) if root is not None else ROOT
    config = json.loads((root / 'data/tasting-menu.json').read_text())
    validate_config(config)
    data = json.loads((root / 'data/tasting-menu-editorial.json').read_text())
    editions = validate_editorial(data, config)
    all_papers = data['papers']
    visible = [p for p in all_papers if config['preview'] or not p.get('example')]
    current = [p for p in visible if p['edition'] == config['edition']['id']]
    if config['preview'] and not current:
        current = [p for p in visible if p.get('example')]
    if current:
        intro = '<p class="tm-note">These papers illustrate the format. They are not nominations for a current cycle, and no community votes or quotes are attached.</p>' if all(p.get('example') for p in current) else ''
        highlights = intro + '<div class="tm-papers">' + '\n'.join(card(p, i + 1) for i, p in enumerate(current)) + '</div>'
    else:
        highlights = '<div class="tm-empty"><strong>The next menu is taking shape.</strong><p>Published highlights will appear here after the community round and editorial review.</p></div>'
    index_path = root / 'tasting-menu.html'
    index = index_path.read_text()
    index = replace_once(r'<!-- highlights:start -->.*?<!-- highlights:end -->', lambda _: '<!-- highlights:start -->\n' + highlights + '\n          <!-- highlights:end -->', index, 'highlights')
    # Keep the static fallback truthful even when JavaScript is disabled.
    preview_notice = '<div class="tm-preview" id="preview-notice"><strong>Design preview</strong><span>A proposal for FLaNN. Example highlights below; nominations have not opened.</span></div>' if config['preview'] else '<div class="tm-preview" id="preview-notice" hidden></div>'
    index = replace_once(r'<div class="tm-preview" id="preview-notice"(?: hidden)?>.*?</div>', lambda _: preview_notice, index, 'preview notice')
    text_values = {
        'edition-label': 'A taste of the format · example edition' if config['preview'] else config['edition']['title'],
    }
    text_values['snapshot-date'], text_values['form-mode'], text_values['form-explanation'] = static_round_text(config)
    text_values['draft-button'] = 'Preview nomination →' if config['preview'] else 'Prepare nomination draft →'
    for element_id, value in text_values.items():
        pattern = r'(<(?P<tag>span|p|button)\b[^>]*\bid="' + re.escape(element_id) + r'"[^>]*>).*?(</(?P=tag)>)'
        index = replace_once(pattern, lambda m: m[1] + escape(value) + m[3], index, element_id)
    if config['preview']:
        nomination_fallback = '<div class="tm-empty"><strong>The first table is still being set.</strong><p>No community nominations have been collected for this preview.</p><a href="#nominate" class="tm-text-link">Try the nomination draft →</a></div>'
    else:
        issues = 'https://github.com/' + config['repository'] + '/issues?q=is%3Aissue+label%3Atasting-menu'
        nomination_fallback = '<div class="tm-empty"><strong>Explore the public recommendations.</strong><p>JavaScript displays the most recently published snapshot here. The original nominations and discussion are available on GitHub.</p>' + link(issues, 'Read public nominations ↗', 'tm-text-link') + '</div>'
    index = replace_once(r'(<div id="nominations"[^>]*>).*?(</div>\s*<noscript>)', lambda m: m[1] + nomination_fallback + m[2], index, 'nomination fallback')
    archive = ''.join('<details><summary>' + escape(edition) + '</summary><ul>' + ''.join('<li><a href="tasting-menu/papers/' + p['id'] + '.html">' + escape(p['title']) + '</a></li>' for p in papers) + '</ul></details>' for edition, papers in editions.items() if edition != config['edition']['id'])
    if not archive:
        archive = '<p class="tm-note">This is the first published edition. Its highlights are above; future editions will join this archive with their selection notes and original discussions.</p>' if editions else '<p class="tm-note">The first edition is still ahead of us. Each published menu will stay here with its papers, selection notes, and original discussions.</p>'
    index = replace_once(r'(<div id="edition-archive">).*?(</div>)', lambda m: m[1] + archive + m[2], index, 'edition archive')
    outputs = {index_path: index}
    paper_dir = root / 'tasting-menu/papers'
    outputs.update({paper_dir / (p['id'] + '.html'): paper_page(p) for p in visible})
    # Retire hidden examples and removed editorial entries, but never unrelated files.
    managed = {paper_dir / (p['id'] + '.html') for p in all_papers}
    managed.update(path for path in paper_dir.glob('*.html') if GENERATED_NOTICE in path.read_text())
    obsolete = sorted(path for path in managed if path.exists() and path not in outputs)
    stale = [str(path.relative_to(root)) for path, content in outputs.items() if not path.exists() or path.read_text() != content]
    if check:
        if stale or obsolete:
            details = stale + [str(path.relative_to(root)) + ' (remove)' for path in obsolete]
            raise ValueError('Generated pages need rebuilding: ' + ', '.join(details))
    else:
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        for path in obsolete:
            path.unlink()
    print(f"{'Checked' if check else 'Built'} {len(outputs)} Tasting Menu pages.")


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated pages need rebuilding')
    args = parser.parse_args()
    try:
        render(args.check)
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'{error}\n')
